func helpdeskSensitivity(s domain.Sensitivity) string {
	switch s {
	case domain.SensitivityLow:
		return "Чувствительность НИЗКАЯ: заводи тикет только на явные проблемы и запросы. При сомнении — is_task = false."
	case domain.SensitivityHigh:
		return "Чувствительность ВЫСОКАЯ: лучше перестраховаться — заводи тикет на любые вопросы и потенциальные проблемы; снижай confidence, если сомневаешься."
	default:
		return "Чувствительность СРЕДНЯЯ: заводи тикет на явные и достаточно вероятные обращения; очевидный шум отсекай."
	}
}

func aboutLine(about string) string {
	if a := strings.TrimSpace(about); a != "" {
		return "О сервисе: " + a
	}
	return ""
}

func helpdeskSystemPrompt(in TriageInput) string {
	return strings.NewReplacer("{{ABOUT}}", aboutLine(in.OwnerAbout),
		"{{SENSITIVITY}}", helpdeskSensitivity(in.Sensitivity)).Replace(helpdeskSystemPromptTemplate)
}

func helpdeskTicketPrompt(in ForwardInput) string {
	return strings.NewReplacer("{{ABOUT}}", aboutLine(in.OwnerAbout)).Replace(helpdeskTicketPromptTemplate)
}
