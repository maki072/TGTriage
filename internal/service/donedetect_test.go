package service

import "testing"

func TestIsDoneMessage(t *testing.T) {
	yes := []string{
		"готово", "Готово!", "готово отключился", "Готово, отключил.", "всё готово", "Всё сделал", "сделано",
		"исправил, проверяйте", "Готово 👍", "готово, включил", "выполнено", "Done", "ГОТОВО",
	}
	no := []string{
		"", "ок", "спасибо", "готово?", "не готово", "ещё не сделал", "будет готово завтра", "когда будет готово",
		"сделаю сегодня", "если будет готово — напишу", "нужно сделать", "не отключился", "почти готово",
		"Готово, но нужно ещё проверить как оно работает на боевом сервере после обновления",
		"Мне нужно чтобы вы сделали отчёт", "давай сделаем", "поздравляю", "как отключился?",
	}
	for _, s := range yes {
		if !IsDoneMessage(s) {
			t.Errorf("IsDoneMessage(%q) = false, want true", s)
		}
	}
	for _, s := range no {
		if IsDoneMessage(s) {
			t.Errorf("IsDoneMessage(%q) = true, want false", s)
		}
	}
}
